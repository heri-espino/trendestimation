import numpy as np
import pytest

ROOT = Path(__file__).resolve().parents[1]
HERE = ROOT / "paper" / "computational-statistics-submission"
sys.path.insert(0, str(HERE))
spec = importlib.util.spec_from_file_location(
    "make_selection_dashboards", HERE/"make_selection_dashboards.py",
)
assert spec and spec.loader
study = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = study
spec.loader.exec_module(study)


def test_factorial_shape_and_methods():
    assert study.ORDERS == (1, 2, 3, 4)
    assert study.SELECTORS == ("cv", "gcv", "aicc", "bic", "mle", "controlled")
    assert study.MU_MODES == ("zero", "data")
    assert len(study.ORDERS)*len(study.SELECTORS) == 24


def test_mle_conditional_mu_and_s_are_correct():
    y = 0.08*np.arange(60) + .5*np.sin(np.arange(60)/6)
    for mode in ("zero", "data"):
        results = study.fitted_selection(y, 2, mode)
        assert len(results) == 6
        assert np.isclose(results["controlled"]["s"], .86, atol=1e-9)
        from trendestimation import TrendSmoother, score_lambda
        model = TrendSmoother(len(y), order=2)
        ref = 0.0 if mode == "zero" else float(np.mean(model.D @ y))
        for selector in study.SELECTORS:
            r = results[selector]
            assert np.isclose(r["mu"], ref)
            assert np.isfinite(r["lambda"]) and r["lambda"] > 0
            assert np.isfinite(r["s"]) and 0 < r["s"] < 1
            if selector != "controlled":
                assert r["candidate_count"] == 29
        mle = results["mle"]
        expect = score_lambda(
            model, y, lambda_=mle["lambda"], criterion="mle",
            mu="data" if mode == "data" else 0.0,
        )
        assert np.isclose(mle["score"], expect)


def test_holdout_estimation_does_not_leak_future():
    from datetime import date
    values = np.linspace(0, 6, 72) + .2*np.sin(np.arange(72)/4)
    dates = study.month_after(date(2019, 12, 1), len(values))
    first = study.analyze(dates, values, "data")
    contaminated = values.copy()
    contaminated[-study.HOLDOUT:] += 1000
    second = study.analyze(dates, contaminated, "data")
    for d in study.ORDERS:
        for method in study.SELECTORS:
            a = first["records"][(d,method)]
            b = second["records"][(d,method)]
            assert np.isclose(a["holdout_mu"], b["holdout_mu"])
            assert np.isclose(a["holdout_lambda"], b["holdout_lambda"])
            assert np.allclose(a["holdout_prediction"],b["holdout_prediction"])
    assert first["records"][(2,"mle")]["holdout_mu"] != 0


