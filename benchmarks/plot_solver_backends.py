"""Make reproducible Marp-ready plots *only* from measured benchmark JSON.

    python benchmarks/plot_solver_backends.py \
      --input build/solver-backends.json --output-dir build/solver-plots

Produces comparisons for single-fit and setup-plus-batch costs.
Plots are generated by an explicit command, never by Sphinx.
"""
from __future__ import annotations

import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt


COLORS = {"svd": "#2863AA", "eigh": "#D5973C", "cholesky": "#13877A"}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    args = parser.parse_args(argv)

    data = json.loads(args.input.read_text(encoding="utf-8"))
    if data.get("kind") != "matched_full_trend_reconstruction":
        parser.error("Input JSON must be a matched full-trend benchmark result")
    output = args.output_dir
    output.mkdir(parents=True, exist_ok=True)
    rows = data["rows"]
    methods = ("svd", "eigh", "cholesky")
    grouped = defaultdict(dict)
    for item in rows:
        key = (item["n"], item["order"], item["evaluations"], item["mu"])
        grouped[key][item["method"]] = item

    # This machine-specific table is suitable for slide-level summaries.
    with (output / "workload_winners.csv").open(
        "w", newline="", encoding="utf-8",
    ) as file:
        writer = csv.writer(file)
        writer.writerow([
            "n", "d", "M", "mu", "winner_setup_plus_batched",
            "winner_single_prepared", "svd_over_cholesky_end_to_end",
            "eigh_over_cholesky_end_to_end",
        ])
        for (n, d, m, mu), group in sorted(grouped.items()):
            if any(method not in group for method in methods):
                continue
            total = {k: group[k]["setup_plus_batched_seconds_median"]
                     for k in methods}
            single = {k: group[k]["single_fit_seconds_median"]
                      for k in methods}
            divisor = total["cholesky"]
            writer.writerow([
                n, d, m, mu, min(total, key=total.get),
                min(single, key=single.get),
                total["svd"] / divisor if divisor > 0 else "",
                total["eigh"] / divisor if divisor > 0 else "",
            ])

    # Plot only workloads with at least two sizes; choose a small set of
    # representative M values to keep the image inventory practical.
    settings = sorted({(d, m, mu) for n, d, m, mu in grouped})
    settings = [
        (d, m, mu) for d, m, mu in settings if d == 2 and mu == 0.0
    ] or settings
    evaluated = 0
    for d, m, mu in settings:
        n_values = sorted({
            n for (n, od, om, omu) in grouped
            if (od, om, omu) == (d, m, mu)
        })
        if len(n_values) < 2:
            continue
        fig, ax = plt.subplots(figsize=(8.4, 4.8), layout="constrained")
        for method in methods:
            xs, ys = [], []
            for n in n_values:
                item = grouped[(n, d, m, mu)].get(method)
                if item is None:
                    continue
                xs.append(n)
                ys.append(1e3 * item["setup_plus_batched_seconds_median"])
            if not xs:
                continue
            ax.plot(
                xs, ys, marker="o", label=method,
                color=COLORS[method], linewidth=2,
            )
        ax.set(
            xlabel="Series length n",
            ylabel="Setup + M full fits (median ms)",
            title=f"Matched PLS full-trend backend comparison | d={d}, M={m}, mu={mu:g}",
        )
        ax.set_yscale("log")
        ax.grid(axis="y", alpha=0.25)
        ax.legend(frameon=False, ncol=3, loc="upper left")
        fig.savefig(output / f"solver_n_d{d}_M{m}_mu{mu:g}.svg")
        fig.savefig(output / f"solver_n_d{d}_M{m}_mu{mu:g}.png", dpi=170)
        plt.close(fig)
        evaluated += 1
        if evaluated >= 4:
            break
    print(f"Generated {evaluated} matched timing plots and workload_winners.csv")


if __name__ == "__main__":
    main()
